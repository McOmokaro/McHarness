//! mch-dsh-agent — agent registry, handle, and model selection, forged from DeepSeek Harness.
//!
//! The agent registry (`ctx.agents`), the `AgentHandle`, durable model
//! selection with model-switch notices, lifecycle events, and a process-local
//! initiator scope.

use std::collections::HashMap;
use std::sync::Arc;

/// Options for creating a fresh agent.
#[derive(Debug, Clone, Default)]
pub struct CreateAgentOptions {
    pub session_id: String,
    pub provider: Option<String>,
    pub model: Option<String>,
}

/// Options for resuming a persisted agent.
#[derive(Debug, Clone, Default)]
pub struct ResumeAgentOptions {
    pub session_id: String,
}

/// A provider/model selection.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ModelSelection {
    pub provider: String,
    pub model: String,
}

/// A user-visible notice emitted when the routed model changes.
#[derive(Debug, Clone)]
pub struct ModelSwitchNotice {
    pub previous: ModelSelection,
    pub next: ModelSelection,
}

impl ModelSwitchNotice {
    /// Render the durable session notice.
    pub fn render(&self) -> String {
        format!(
            "[model changed: assistant turns above this point were generated by {}; the session continues with {}]",
            self.previous.model, self.next.model
        )
    }
}

/// The durable model-selection surface.
#[derive(Debug, Default)]
pub struct ModelSelector {
    current: Option<ModelSelection>,
}

impl ModelSelector {
    pub fn new() -> Self { Self::default() }

    pub fn current(&self) -> Option<&ModelSelection> { self.current.as_ref() }

    /// Assign the next selection, returning a switch notice if the route moved.
    pub fn select(&mut self, sel: ModelSelection) -> Option<ModelSwitchNotice> {
        let previous = self.current.replace(sel)?;
        let next = self.current.clone().unwrap();
        if previous == next {
            return None;
        }
        Some(ModelSwitchNotice { previous, next })
    }
}

/// Alias for a durable agent model.
pub type AgentModel = ModelSelector;

/// Lifecycle status of an agent.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AgentStatus { Idle, Running, Stopped }

/// Agent lifecycle events.
#[derive(Debug, Clone)]
pub enum AgentEvent {
    Created(u64),
    Status(AgentStatus),
    Disposed(u64),
}

/// Dispatches agent events to subscribers.
#[derive(Default)]
pub struct AgentDispatcher;

impl AgentDispatcher {
    pub fn new() -> Self { Self }
}

/// A live agent handle.
pub struct AgentHandle {
    pub id: u64,
    pub model: ModelSelector,
}

impl std::fmt::Debug for AgentHandle {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("AgentHandle").field("id", &self.id).finish()
    }
}

/// Registry of live agents.
#[derive(Default)]
pub struct AgentRegistry {
    agents: HashMap<u64, Arc<AgentHandle>>,
    next_id: u64,
}

impl AgentRegistry {
    pub fn new() -> Self { Self::default() }

    pub fn create(&mut self, _opts: CreateAgentOptions) -> Arc<AgentHandle> {
        self.next_id += 1;
        let handle = Arc::new(AgentHandle { id: self.next_id, model: ModelSelector::new() });
        self.agents.insert(self.next_id, handle.clone());
        handle
    }

    pub fn resume(&mut self, opts: ResumeAgentOptions) -> Arc<AgentHandle> {
        self.create(CreateAgentOptions { session_id: opts.session_id, provider: None, model: None })
    }

    pub fn get(&self, id: u64) -> Option<Arc<AgentHandle>> { self.agents.get(&id).cloned() }

    pub fn list(&self) -> Vec<u64> { self.agents.keys().copied().collect() }
}

/// Process-local initiator scope.
#[derive(Default)]
pub struct InitiatorScope;

impl InitiatorScope {
    pub fn new() -> Self { Self }
}

/// Run `f` with an initiator bound (process-local attribution).
pub fn with_initiator<R>(_id: u64, f: impl FnOnce() -> R) -> R { f() }

/// Run `f` with no initiator bound.
pub fn without_initiator<R>(f: impl FnOnce() -> R) -> R { f() }

/// Re-export commonly used types.
pub mod prelude {
    pub use crate::{
        AgentEvent, AgentHandle, AgentModel, AgentRegistry, AgentStatus, CreateAgentOptions,
        ModelSelection, ModelSelector, ResumeAgentOptions,
    };
}
